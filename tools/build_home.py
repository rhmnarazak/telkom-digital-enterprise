def fill(s, name, body):
    pat = re.compile(rf'(  <!-- @gen:{name} -->\n).*?(  <!-- /@gen:{name} -->)', re.S)
    s, n = pat.subn(lambda m: m.group(1) + body + "\n" + m.group(2), s)
    assert n == 1, name
    return s


def main():
    path = ROOT / "index.html"
    s = path.read_text(encoding="utf-8")
    m = re.search(r'<ul class="mitra-track">.*?</ul>', s, re.S)
    if m:
        mitra = m.group(0)
    else:
        mitra = re.search(r'<ul class="mitra-track">.*?</ul>', (ROOT / "who-we-are.html").read_text(encoding="utf-8"), re.S).group(0)
    s = fill(s, "services", services())
    s = fill(s, "stack", stack())
    s = fill(s, "proof", proof(mitra))
    s = fill(s, "who", who())
    path.write_text(s, encoding="utf-8")
    print("updated index.html (services, stack, proof, who)")


if __name__ == "__main__":
    main()
